CREATE PROC [dbo].[USP_CUESTIONARIO_PREGUNTA_ALL]
	@ID_CUESTIONARIO INT
AS
BEGIN
	DECLARE @ALL_ROWS bigint = 0;

	SELECT @ALL_ROWS = COUNT(1)
	FROM dbo.CUESTIONARIO_PREGUNTA
	WHERE ID_CUESTIONARIO = @ID_CUESTIONARIO;

	SELECT
	ROW_NUMBER() OVER(ORDER BY ID_CUESTIONARIO_PREGUNTA) AS FILA
	, @ALL_ROWS AS REGISTROS
	, ID_CUESTIONARIO_PREGUNTA
	, NOMBRE
	, PESO
	, ID_CUESTIONARIO
	FROM dbo.CUESTIONARIO_PREGUNTA
	WHERE ID_CUESTIONARIO = @ID_CUESTIONARIO;
END
GO

