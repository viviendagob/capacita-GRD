CREATE PROC [dbo].[USP_CUESTIONARIO_PREGUNTA_DEL_ALL]
	@ID_CUESTIONARIO INT
AS
BEGIN
	SET NOCOUNT ON;

	DELETE R
	FROM dbo.CUESTIONARIO_PREGUNTA_RESPUESTA R
	INNER JOIN dbo.CUESTIONARIO_PREGUNTA P ON P.ID_CUESTIONARIO_PREGUNTA = R.ID_CUESTIONARIO_PREGUNTA
	WHERE P.ID_CUESTIONARIO = @ID_CUESTIONARIO;

	DELETE FROM dbo.CUESTIONARIO_PREGUNTA
	WHERE ID_CUESTIONARIO = @ID_CUESTIONARIO;
END
GO

